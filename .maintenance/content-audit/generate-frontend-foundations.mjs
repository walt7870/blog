import fs from 'node:fs';

const output = new URL('../../public/front/frontend-foundations-series/', import.meta.url);
const esc = s => String(s).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const t = (x,y,s,cls='s') => `<text x="${x}" y="${y}" class="${cls}">${esc(s)}</text>`;
const box = (x,y,w,h,title,lines=[],cls='node') => `<g data-node="${esc(title)}"><rect x="${x}" y="${y}" width="${w}" height="${h}" rx="6" class="${cls}"/>${t(x+18,y+32,title,'n')}${lines.map((s,i)=>t(x+18,y+62+i*27,s)).join('')}</g>`;
const edge = d => `<path d="${d}" class="edge"/>`;
function svg(ep,title,desc,height,body,notes=[]) {
  fs.writeFileSync(new URL(`ep${String(ep).padStart(2,'0')}-flow.svg`,output),`<svg xmlns="http://www.w3.org/2000/svg" width="1120" height="${height}" viewBox="0 0 1120 ${height}" role="img" aria-labelledby="title desc"><title id="title">${esc(title)}</title><desc id="desc">${esc(desc)}</desc><defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0 0L8 4L0 8Z" fill="#607568"/></marker><style>text{font-family:-apple-system,'PingFang SC','Microsoft YaHei',sans-serif;letter-spacing:0;fill:#253c30}.h{font-size:28px;font-weight:600}.n{font-size:21px;font-weight:600}.s{font-size:18px;fill:#52685b}.node{fill:#fff;stroke:#a6b9ad;stroke-width:1.5}.info{fill:#edf3fb;stroke:#739bbf;stroke-width:1.5}.good{fill:#e9f4ee;stroke:#397657;stroke-width:1.5}.warn{fill:#f8eef1;stroke:#ae7789;stroke-width:1.5}.edge{fill:none;stroke:#607568;stroke-width:2;marker-end:url(#arrow)}</style></defs><rect width="1120" height="${height}" fill="white"/>${t(32,44,title,'h')}${t(32,82,desc)}${body}${notes.map((s,i)=>t(32,height-28-(notes.length-1-i)*28,s)).join('')}</svg>\n`);
}

// 新图使用独立ID，避免将来内联引用时与其他图冲突。
function prefixIds(ep) {
  const file = new URL(`ep${String(ep).padStart(2,'0')}-flow.svg`, output);
  const content = fs.readFileSync(file, 'utf8');
  fs.writeFileSync(file, content.replace('aria-labelledby="title desc"', `aria-labelledby="ep${ep}-title ep${ep}-desc"`).replace('id="title"', `id="ep${ep}-title"`).replace('id="desc"', `id="ep${ep}-desc"`));
}

